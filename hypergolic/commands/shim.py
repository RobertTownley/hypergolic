"""The program that stands in for a command inside the sandbox.

Deliberately dumb: it holds no policy, only transport. It cannot know the command
that triggered it — given ``analytics query x && rm -rf /tmp/probe`` the shell
forks it with ``argv = ["query", "x"]`` and the ``&&`` clause never arrives — so
it echoes back the injected ``HG_EXEC_ID`` and lets the server, which issued the
exec, resolve the originating string and session identity on its own.

A shim is not authority. The agent may write a lookalike anywhere and gain
nothing: the server resolves against its own registry, keyed on the session the
bearer token establishes.

The shebang targets ``/usr/local/bin/hg-python``, the pinned uv-managed
interpreter every workspace image installs at build (see
``REQUIRED_BUILD_STEPS``) — never the project's own python. Stdlib only. The broker pings every 15s while a command runs, so an
idle stream never looks dead to OrbStack's NAT (which drops silent connections
without a reset); the shim's 60s read timeout turns a dead connection into a
nonzero exit so ``&&`` short-circuits rather than hanging until the exec
timeout discards the result.
"""

from __future__ import annotations

#: ``70`` is EX_SOFTWARE: distinct from any exit code a real command would use
#: for its own failure, so a transport problem is never mistaken for success.
TRANSPORT_FAILURE_EXIT = 70

SHIM_SOURCE = '''#!/usr/local/bin/hg-python
"""Generated by Hypergolic. Transport only; the real implementation is on the
host. See /tools/<name>/source."""
import json
import os
import sys
import urllib.request

EX_SOFTWARE = 70
NAME = os.path.basename(sys.argv[0])
ARGS = sys.argv[1:]

# `@-` (curl's convention) marks an argument whose value arrives on stdin,
# letting a quoted heredoc carry text no shell quoting survives. Reading is
# gated on the marker so a shim never drains a pipeline it wasn't told to.
STDIN = None
if any(a == "@-" or a.endswith("=@-") for a in ARGS):
    STDIN = sys.stdin.read()

if ARGS and ARGS[0] in ("--help", "-h"):
    try:
        with open(f"/tools/{NAME}/README.md") as fh:
            sys.stdout.write(fh.read())
        sys.exit(0)
    except OSError as exc:
        print(f"no help for {NAME}: {exc}", file=sys.stderr)
        sys.exit(EX_SOFTWARE)

broker = os.environ.get("HG_BROKER")
token = os.environ.get("HG_TOKEN")
if not broker or not token:
    print(
        f"{NAME}: no broker in this environment. Host commands are reachable "
        "only from a process started by a tool call.",
        file=sys.stderr,
    )
    sys.exit(EX_SOFTWARE)

request = urllib.request.Request(
    f"http://{broker}/broker/invoke",
    data=json.dumps(
        {
            "command": NAME,
            "argv": ARGS,
            "stdin": STDIN,
            "cwd": os.getcwd(),
            "exec_id": os.environ.get("HG_EXEC_ID"),
        }
    ).encode(),
    headers={
        "Authorization": f"Bearer {token}",
        "Content-Type": "application/json",
    },
)

try:
    with urllib.request.urlopen(request, timeout=60) as response:
        for line in response:
            if not line.strip():
                continue
            frame = json.loads(line)
            kind = frame.get("type")
            if kind == "stdout":
                sys.stdout.write(frame["data"])
                sys.stdout.flush()
            elif kind == "stderr":
                sys.stderr.write(frame["data"])
                sys.stderr.flush()
            elif kind == "exit":
                sys.exit(frame["code"])
except SystemExit:
    raise
except Exception as exc:  # noqa: BLE001 - any transport failure must be visible
    print(f"{NAME}: broker unreachable: {exc}", file=sys.stderr)
    sys.exit(EX_SOFTWARE)

print(f"{NAME}: broker closed the stream without an exit status", file=sys.stderr)
sys.exit(EX_SOFTWARE)
'''
