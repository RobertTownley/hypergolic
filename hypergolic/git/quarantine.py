"""Per-session bare quarantine repos: the push transport out of a sandbox.

Every session gets hypergolic-owned bare repos under
``~/.hypergolic_internals/quarantine/<session>/<repo>.git``, mounted rw at
``/quarantine/<repo>.git`` in that session's sandbox only. The clone's
``origin`` has split URLs: fetch from the host repo's gitdir (mounted
read-only at its host-true path, so refs are always live), push to the
quarantine. Objects stay thin: the quarantine alternates into the host
repo's object store, and the alternates path — being host-true — resolves
identically in the container and on the host (spike: unresolvable alternate
lines work but print errors on every push).

A push to any ``refs/heads/<branch>`` is a land request for host branch
``<branch>``: the update hook calls the broker's ``land`` command and streams
the gate pipeline's verdict back as ``remote:`` lines; landing happens
host-side, and post-receive deletes the quarantine's ref again so the next
land push is never non-fast-forward.
The update hook (not pre-receive) because the land call needs to *fetch* the
pushed sha from the quarantine, and during pre-receive the objects still sit
in receive-pack's incoming quarantine dir, invisible to a host-side fetch.
System code moves session state host-side through ``refs/hypergolic/checkpoint/*``
(:func:`checkpoint_ref`), which the hooks accept silently — branch names and
checkpoints never share a namespace, so a checkpoint can never land.

The host never trusts quarantine refs; it only ever *fetches* them into the
session-namespaced ``refs/hypergolic/...`` of the target repo, or reads the
sha a validated land request names. Session conclusion deletes the session's
quarantine dir wholesale.
"""

from __future__ import annotations

import shutil
from pathlib import Path

from hypergolic.config.settings import INTERNALS_DIR
from hypergolic.git.commands import GitResult, async_run_git_command, run_git_command

QUARANTINE_MOUNT_ROOT = "/quarantine"

_UPDATE_HOOK = r"""#!/bin/sh
# Generated by Hypergolic. A push to refs/heads/<branch> is a land request:
# the broker runs this repo's merge gates and, if they pass, lands the work
# on the host branch (squashed or fast-forwarded per project/`-o mode=`); each
# `-o description=` adds one line to the reviewer-facing description. Other refs (checkpoints) are accepted as-is.
case "$1" in refs/heads/*) ;; *) exit 0 ;; esac
case "$3" in *[!0]*) ;; *) exit 0 ;; esac
msg=""
mode=""
desc=""
nl="
"
i=0
while [ "$i" -lt "${GIT_PUSH_OPTION_COUNT:-0}" ]; do
  eval "opt=\${GIT_PUSH_OPTION_$i}"
  case "$opt" in
    message=*) msg="${opt#message=}" ;;
    mode=*) mode="${opt#mode=}" ;;
    description=*) desc="${desc:+$desc$nl}${opt#description=}" ;;
  esac
  i=$((i+1))
done
# Only flags the push named: a default push must also land on an older host `land`.
set -- --repo %REPO% --branch "${1#refs/heads/}" --sha "$3"
[ -n "$msg" ] && set -- "$@" --message "$msg"
[ -n "$mode" ] && set -- "$@" --mode "$mode"
[ -n "$desc" ] && set -- "$@" --description "$desc"
exec /tools/bin/land "$@"
"""

_POST_RECEIVE_HOOK = """#!/bin/sh
# Generated by Hypergolic. A landed branch ref must not linger: the next land
# push would be non-fast-forward against it. The land itself happened
# host-side; this ref is transport residue.
while read old new ref; do
  case "$ref" in refs/heads/*) git update-ref -d "$ref" "$new" ;; esac
done
exit 0
"""


def session_quarantine_dir(session_id: str) -> Path:
    return INTERNALS_DIR / "quarantine" / session_id


def quarantine_path(session_id: str, repo: str) -> Path:
    """Host path of the session's bare quarantine repo for *repo*."""
    return session_quarantine_dir(session_id) / f"{repo}.git"


def quarantine_mount(repo: str) -> str:
    """Container path of the quarantine (the clone's push URL)."""
    return f"{QUARANTINE_MOUNT_ROOT}/{repo}.git"


def checkpoint_ref(name: str) -> str:
    return f"refs/hypergolic/checkpoint/{name}"


def hook_sources(repo: str) -> dict[str, str]:
    return {
        "update": _UPDATE_HOOK.replace("%REPO%", repo),
        "post-receive": _POST_RECEIVE_HOOK,
    }


def ensure_quarantine(*, session_id: str, repo: str, host_gitdir: Path) -> Path:
    """Create (idempotently) the session's quarantine repo for *repo*.

    Host-side, before the sandbox mounts it. The hooks are
    rewritten every time: it is Hypergolic's, not the agent's, even though
    the agent can technically edit it — tampering only skips *asking*.
    """
    path = quarantine_path(session_id, repo)
    if not (path / "HEAD").exists():
        path.mkdir(parents=True, exist_ok=True)
        run_git_command("init", "--quiet", "--bare", ".", cwd=path, check=True)
    (path / "objects" / "info" / "alternates").write_text(f"{host_gitdir}/objects\n")
    run_git_command(
        "config", "receive.advertisePushOptions", "true", cwd=path, check=True,
    )
    # The land call fetches the pushed sha (never a ref) out of the quarantine.
    run_git_command(
        "config", "uploadpack.allowAnySHA1InWant", "true", cwd=path, check=True,
    )
    for name, source in hook_sources(repo).items():
        hook = path / "hooks" / name
        hook.write_text(source)
        hook.chmod(0o755)
    return path


def delete_session_quarantines(session_id: str) -> None:
    """Remove every quarantine repo of the session. Best-effort."""
    shutil.rmtree(session_quarantine_dir(session_id), ignore_errors=True)


async def fetch_quarantine_ref(
    *, host_repo: Path, session_id: str, repo: str, src_ref: str, dst_ref: str,
) -> GitResult:
    """Fetch a quarantine ref into *host_repo* (forced: sessions amend)."""
    return await async_run_git_command(
        "fetch", "--quiet", "--no-write-fetch-head",
        str(quarantine_path(session_id, repo)), f"+{src_ref}:{dst_ref}",
        cwd=host_repo,
    )
